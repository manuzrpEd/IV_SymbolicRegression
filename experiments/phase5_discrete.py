"""THEORY.md §5 (Proposition 4) in the data: with a J-point instrument, a wrong formula with J constants can zero the criterion.

    python experiments/phase5_discrete.py      -> experiments/phase5/discrete.md

Design D4 has a four-point instrument, so the orthonormalized criterion has K = 4 moments. On 20,000 noise-free draws
(f0 in place of y, so the criterion measures separation only), the wrong four-term formula
c0 + c1 sqrt(x) + c2 x + c3 x^2 is fitted to the moments by first-step GMM, for each one-regressor law. Reported: the
criterion ||A'r||^2 / n at the fit, the RMS distance of the fitted formula from f0 in units of sd(f0), whether a constant
sits at its bound, and for contrast the same formula's criterion under D1, whose continuous instrument gives K ~ n^(1/3).
"""

from __future__ import annotations

import sys
import warnings
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).parent))
from symiv.criteria import gmm_criterion  # noqa: E402
from symiv.dgp import simulate  # noqa: E402
from symiv.expressions import parametrize  # noqa: E402
from symiv.gmm import fit_gmm  # noqa: E402

OUT = Path(__file__).parent / "phase5" / "discrete.md"
FORMULA = "0.5 + 0.5*sqrt(x0) + 0.5*x0 + 0.5*x0**2"
LAWS = {"log": "1 + 2 log x", "power": "2 x^0.7", "kink": "x − 0.8 max(x − 1.5, 0)", "saturation": "3x / (1 + x)"}
N, BOUND = 20_000, 10.0


def check(design: str, law: str) -> dict:
    s = simulate(design, law, n=N, seed=0)
    crit = gmm_criterion(s.Z)
    form = parametrize(FORMULA, 1)
    fit = fit_gmm(form, s.X, s.f0, crit, bound=BOUND, n_starts=6, seed=0)
    r = s.f0 - form(s.X, fit.theta)
    return dict(K=crit.K, Q=crit.value(r), dist=float(np.sqrt(np.mean(r**2)) / s.f0.std()),
                at_bound=bool(np.any(np.abs(fit.theta) > 0.999 * BOUND)), theta=fit.theta.tolist())


def main() -> None:
    warnings.filterwarnings("ignore")
    sys.stdout.reconfigure(encoding="utf-8")
    L = ["# Discrete instruments: a wrong four-constant formula against four moments (Proposition 4)\n",
         f"Generated by `experiments/phase5_discrete.py`. {N:,} noise-free draws; the formula `{FORMULA}` (four constants, "
         f"|c| ≤ {BOUND:g}) fitted to the moments of f₀ by first-step GMM. Q = ‖A′r‖²/n at the fit; distance = RMS(f − f₀)/sd(f₀).\n",
         "| Law | D4 (J = 4): K | D4: Q at the fit | D4: distance from f₀ | D4: a constant at the bound | D1 (continuous Z): K | D1: Q at the fit | D1: distance |",
         "|---|---|---|---|---|---|---|---|"]
    for law, label in LAWS.items():
        d4, d1 = check("D4", law), check("D1", law)
        L.append(f"| {label} | {d4['K']} | {d4['Q']:.1e} | {d4['dist']:.2f} | {'yes' if d4['at_bound'] else 'no'} | "
                 f"{d1['K']} | {d1['Q']:.1e} | {d1['dist']:.2f} |")
    L.append("")
    L.append("With four moments the four-constant formula can match them exactly whenever the moment equations have a solution "
             "within the constant bound (Proposition 4(a)): the criterion is then numerically zero while the formula is far from f₀. "
             "With the continuous instrument the same formula is separated from f₀.")
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
