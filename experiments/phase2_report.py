"""Tables for Phase 2 from experiments/phase2/runs.jsonl -> experiments/phase2/summary.md."""

from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

import numpy as np

HERE = Path(__file__).parent / "phase2"
TRUE = {"power": {"a": 2.0, "theta": 0.7}, "log": {"a": 1.0, "b": 2.0}}
LAWS = {"power": "2 x^0.7", "log": "1 + 2 log x"}
SETTINGS = {"default": "default (π = 1, ρ = 0.8)", "strong": "strong (π = 0.7, ρ = 1.2)"}
METHODS = [  # (label, path into a run record)
    ("Plain PySR, PySR's pick", ("plain", "pysr_pick")),
    ("Plain PySR, BIC", ("plain", "bic")),
    ("Symbolic IV, BIC", ("iv", "bic")),
    ("Symbolic IV, HQIC", ("iv", "hqic")),
    ("Symbolic IV, AIC", ("iv", "aic")),
    ("Oracle LS (true form)", ("oracle_ls",)),
    ("Oracle IV (true form)", ("oracle_iv",)),
]


def get(run: dict, path: tuple) -> dict:
    for k in path:
        run = run[k]
    return run


def wilson(k: int, n: int, z: float = 1.96) -> str:
    """Rate with a 95% Wilson interval."""
    if n == 0:
        return "–"
    p = k / n
    centre = (p + z**2 / (2 * n)) / (1 + z**2 / n)
    half = z * np.sqrt(p * (1 - p) / n + z**2 / (4 * n**2)) / (1 + z**2 / n)
    return f"{k}/{n} ({100 * p:.0f}%, {100 * max(0, centre - half):.0f}–{100 * min(1, centre + half):.0f})"


def med(xs) -> str:
    """Median, ignoring NaN (undefined, e.g. an elasticity where f_hat = 0); inf still counts."""
    xs = np.asarray([x for x in xs if x is not None], dtype=float)
    xs = xs[~np.isnan(xs)]
    if xs.size == 0:
        return "–"
    m = np.median(xs)
    return "∞" if np.isinf(m) else f"{m:.3f}"


def med_iqr(xs) -> str:
    xs = np.asarray([x for x in xs if x is not None and np.isfinite(x)], dtype=float)
    if xs.size == 0:
        return "–"
    q1, m, q3 = np.percentile(xs, [25, 50, 75])
    return f"{m:.3f} [{q1:.3f}, {q3:.3f}]"


def key(r: dict) -> tuple:
    return (r["part"], r["law"], r["setting"], r["seed"], r["K"], r["C"])


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    runs = [json.loads(line) for line in (HERE / "runs.jsonl").read_text().splitlines() if line.strip()]
    ok = {key(r) for r in runs if "error" not in r}
    errors = [r for r in runs if "error" in r and key(r) not in ok]  # errored and never rerun successfully
    runs = [r for r in runs if "error" not in r]
    main_runs = [r for r in runs if r["part"] == "main"]
    sens_runs = [r for r in runs if r["part"] == "sensitivity"]
    L = []
    w = L.append

    w("# Phase 2 results: plain PySR vs. symbolic IV on design D1\n")
    w(f"Generated by `experiments/phase2_report.py` from {len(runs)} runs in `runs.jsonl` ({len(errors)} errored).\n")
    w("Setup: n = 2000; PySR with `niterations=40`, `maxsize=15`, operators +, −, ×, ÷, ^, max, log, exp; "
      "GMM criterion with cubic-spline instruments (K = 13); constant bound C = 10 for symbolic IV; "
      "plain PySR unbounded. Selection from each Pareto front after refitting constants: "
      "least squares with n log(RSS/n) + p κₙ for plain PySR, two-step GMM with MMSC = J − (K − p) κₙ for symbolic IV; "
      "κₙ = ln n (BIC), 2.01 ln ln n (HQIC), 2 (AIC). Errors are RMS(f̂ − f₀) in units of the in-sample sd of f₀; "
      "extrapolation is on [q₉₉, 3 q₉₉] of X. Rates show 95% Wilson intervals.\n")

    for law in LAWS:
        for setting in SETTINGS:
            rs = [r for r in main_runs if r["law"] == law and r["setting"] == setting]
            if not rs:
                continue
            w(f"\n## {LAWS[law]}, {SETTINGS[setting]}: {len(rs)} seeds\n")
            names = list(TRUE[law])
            w("| Method | Form recovered | In-sample error, median | Extrapolation error, median | "
              f"Elasticity at median X (true {np.median([r['elasticity_true'] for r in rs]):.2f}) | "
              + " | ".join(f"{n} (true {TRUE[law][n]}), median [IQR]" for n in names) + " |")
            w("|---|---|---|---|---|" + "---|" * len(names))
            for label, path in METHODS:
                ds = [get(r, path) for r in rs]
                k = sum(d["recovered"] for d in ds)
                consts = [med_iqr([d["implied"][j] for d in ds]) for j in range(len(names))]
                w(f"| {label} | {wilson(k, len(ds))} | {med(d['rel_error'] for d in ds)} | "
                  f"{med(d['extrap_error'] for d in ds)} | {med(d['elasticity'] for d in ds)} | " + " | ".join(consts) + " |")
            w("\nConstants are those of the true form that best reproduce each selected formula (exact when the form is right).\n")

    w("\n## Symbolic IV outcomes (README §7 diagnostic)\n")
    w("Success: the selected formula has the true form. Search failure: the true form has a lower MMSC than the selected "
      "formula, so the search missed it. Statistical failure: the criterion itself prefers the wrong formula.\n")
    w("| Law | Setting | Penalty | Success | Search failure | Statistical failure | MMSC gap to runner-up, median | Pareto-front size, median |")
    w("|---|---|---|---|---|---|---|---|")
    for law in LAWS:
        for setting in SETTINGS:
            rs = [r for r in main_runs if r["law"] == law and r["setting"] == setting]
            for pen in ("bic", "hqic", "aic"):
                if not rs:
                    continue
                c = Counter(r["iv"][pen]["outcome"] for r in rs)
                w(f"| {LAWS[law]} | {setting} | {pen.upper()} | {c['success']} | {c['search_failure']} | "
                  f"{c['statistical_failure']} | {med(r['iv'][pen]['gap'] for r in rs)} | {med(r['front_size'] for r in rs)} |")

    if sens_runs:
        w("\n## Sensitivity to K and C (power law, strong setting, symbolic IV with BIC)\n")
        w("| K | C | Seeds | Form recovered | Success / search / statistical | In-sample error, median | Extrapolation error, median |")
        w("|---|---|---|---|---|---|---|")
        seeds = sorted({r["seed"] for r in sens_runs})
        base = [r for r in main_runs if r["law"] == "power" and r["setting"] == "strong" and r["seed"] in seeds]
        groups = [((13, 10.0, "(main grid)"), base)] + [
            ((K, C, ""), [r for r in sens_runs if r["K_used"] == K and r["C"] == C])
            for K, C in sorted({(r["K_used"], r["C"]) for r in sens_runs})
        ]
        for (K, C, note), rs in groups:
            if not rs:
                continue
            c = Counter(r["iv"]["bic"]["outcome"] for r in rs)
            k = sum(r["iv"]["bic"]["recovered"] for r in rs)
            w(f"| {K} {note} | {C:g} | {len(rs)} | {wilson(k, len(rs))} | {c['success']} / {c['search_failure']} / "
              f"{c['statistical_failure']} | {med(r['iv']['bic']['rel_error'] for r in rs)} | "
              f"{med(r['iv']['bic']['extrap_error'] for r in rs)} |")

    w("\n## Runtime\n")
    w(f"Median seconds per search: plain PySR {med(r['time_plain'] for r in main_runs)}, "
      f"symbolic IV {med(r['time_iv'] for r in runs)}.\n")
    if errors:
        w("\n## Errors\n")
        for r in errors:
            w(f"- {r['law']} {r['setting']} seed {r['seed']} K={r['K']} C={r['C']}: `{r['error'].strip().splitlines()[-1]}`")

    (HERE / "summary.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
