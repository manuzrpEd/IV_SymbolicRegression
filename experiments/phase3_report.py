"""Tables for Phase 3 -> experiments/phase3/summary.md.

Reads experiments/phase3/runs-*.jsonl, plus experiments/phase2/runs.jsonl for
symbolic IV and plain PySR on D1 (same seeds, same data).
"""

from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

import numpy as np

from phase2_report import med, wilson

HERE = Path(__file__).parent
LAWS = {"power": "2 x^0.7", "log": "1 + 2 log x"}
CELLS = {
    ("D1", "default"): "D1 confounding, default (π = 1, ρ = 0.8)",
    ("D1", "strong"): "D1 confounding, strong (π = 0.7, ρ = 1.2)",
    ("D2", "default"): "D2 heteroskedastic first stage (π = 1, ρ = 0.8, γ = 0.3)",
}
METHODS = [  # key, label
    ("symbolic_iv_bic", "**Symbolic IV (BIC)**"),
    ("plain_pick", "Plain PySR, PySR's pick"),
    ("plain_bic", "Plain PySR, BIC"),
    ("oracle_iv", "Oracle IV (true form)"),
    ("wrong_linear_iv", "IV, assumed linear form"),
    ("wrong_log_iv", "IV, assumed log form"),
    ("wrong_power_iv", "IV, assumed power form"),
    ("library_iv", "Library + sparse IV"),
    ("sieve_iv", "Sieve 2SLS (curve)"),
    ("kiv", "Kernel IV (curve)"),
    ("deepiv", "DeepIV (curve)"),
    ("distill_sieve_iv_pick", "Sieve 2SLS → PySR, PySR's pick"),
    ("distill_sieve_iv_mmsc", "Sieve 2SLS → PySR, MMSC"),
    ("distill_kiv_pick", "KIV → PySR, PySR's pick"),
    ("distill_kiv_mmsc", "KIV → PySR, MMSC"),
    ("distill_deepiv_pick", "DeepIV → PySR, PySR's pick"),
    ("distill_deepiv_mmsc", "DeepIV → PySR, MMSC"),
    ("control_function_sr", "Control-function SR"),
    ("srit_style", "SRIT-style (reimplementation)"),
]
HEADLINE = ["symbolic_iv_bic", "plain_pick", "library_iv", "sieve_iv", "distill_sieve_iv_pick", "distill_sieve_iv_mmsc",
            "control_function_sr", "srit_style"]


def load() -> dict[tuple, dict]:
    """(design, setting, law, seed) -> {method: record}."""
    runs: dict[tuple, dict] = {}
    for f in sorted((HERE / "phase3").glob("runs-*.jsonl")):
        for line in f.read_text().splitlines():
            if line.strip():
                r = json.loads(line)
                runs[(r["design"], r["setting"], r["law"], r["seed"])] = dict(r["methods"], _errors=r["errors"])
    for line in (HERE / "phase2" / "runs.jsonl").read_text().splitlines():
        r = json.loads(line) if line.strip() else None
        if not r or "error" in r or r["part"] != "main":
            continue
        k = ("D1", r["setting"], r["law"], r["seed"])
        if k in runs:
            runs[k].update(
                symbolic_iv_bic=dict(r["iv"]["bic"], kind="formula", time=r["time_iv"]),
                plain_pick=dict(r["plain"]["pysr_pick"], kind="formula", time=r["time_plain"]),
                plain_bic=dict(r["plain"]["bic"], kind="formula", time=r["time_plain"]),
            )
    return runs


def _true_elasticity(cell: tuple, law: str, seed: int) -> float:
    from phase3 import CELLS as PARAMS

    from symiv.dgp import simulate
    from symiv.metrics import elasticity

    s = simulate(cell[0], law, n=2000, seed=seed, **PARAMS[cell])
    return elasticity(s.law.expr, float(np.median(s.X[:, 0])))


def cell_rows(runs: dict, cell: tuple, law: str) -> list[dict]:
    return [m for (d, s, l, _), m in sorted(runs.items()) if (d, s) == cell and l == law]


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    runs = load()
    L = []
    w = L.append
    n_err = sum(len(m["_errors"]) for m in runs.values())
    w("# Phase 3 results: baselines\n")
    w(f"Generated by `experiments/phase3_report.py` from {len(runs)} runs ({n_err} method errors). "
      "Same data as Phase 2 for D1 (symbolic IV and plain PySR taken from Phase 2); n = 2000; "
      "50 seeds per cell except DeepIV and its distillations (first 20 seeds). Errors are RMS(f̂ − f₀) in units of the "
      "in-sample sd of f₀; extrapolation is on [q₉₉, 3 q₉₉] of X. \"Beats symbolic IV\" is the share of seeds "
      "where the method's in-sample error is lower than symbolic IV's on the same data. Curves (sieve, KIV, DeepIV) "
      "give no formula, so form recovery does not apply. Runtimes are with two runs in parallel on 8 cores, "
      "so they are about twice Phase 2's single-process times.\n")

    # Headline: recovery and in-sample error for the key methods, all cells.
    w("## Headline\n")
    w("| Cell | Law | " + " | ".join(dict(METHODS)[k].strip("*") for k in HEADLINE) + " |")
    w("|---|---|" + "---|" * len(HEADLINE))
    for cell in CELLS:
        for law in LAWS:
            rows = cell_rows(runs, cell, law)
            if not rows:
                continue
            cells = []
            for k in HEADLINE:
                ds = [r[k] for r in rows if k in r]
                if not ds:
                    cells.append("–")
                    continue
                rate = f"{100 * np.mean([d['recovered'] for d in ds]):.0f}%, " if ds[0]["kind"] == "formula" else ""
                cells.append(f"{rate}{med(d['rel_error'] for d in ds)}")
            w(f"| {cell[0]} {cell[1]} | {LAWS[law]} | " + " | ".join(cells) + " |")
    w("\nEach entry: form recovered (formulas only), then median in-sample error.\n")

    for cell, title in CELLS.items():
        for law in LAWS:
            rows = cell_rows(runs, cell, law)
            if not rows:
                continue
            true_el = np.median([_true_elasticity(cell, law, seed) for seed in range(len(rows))])
            w(f"\n## {title}; f₀ = {LAWS[law]}: {len(rows)} seeds\n")
            w(f"True elasticity at the median X: {true_el:.3f} (median over seeds).\n")
            w("| Method | Seeds | Form recovered | In-sample error, median | Extrapolation error, median | "
              "Elasticity at median X, median | Beats symbolic IV | Seconds, median |")
            w("|---|---|---|---|---|---|---|---|")
            for k, label in METHODS:
                pairs = [(r[k], r.get("symbolic_iv_bic")) for r in rows if k in r]
                if not pairs:
                    continue
                ds = [p[0] for p in pairs]
                rec = wilson(sum(d["recovered"] for d in ds), len(ds)) if ds[0]["kind"] == "formula" else "–"
                beats = [d["rel_error"] < iv["rel_error"] for d, iv in pairs if iv is not None]
                beat = "–" if k == "symbolic_iv_bic" or not beats else f"{100 * np.mean(beats):.0f}%"
                w(f"| {label} | {len(ds)} | {rec} | {med(d['rel_error'] for d in ds)} | {med(d['extrap_error'] for d in ds)} | "
                  f"{med(d['elasticity'] for d in ds)} | {beat} | {med(d.get('time') for d in ds)} |")
            srit = Counter(",".join(r["srit_style"]["retained"]) for r in rows if "srit_style" in r)
            lib = Counter(" + ".join(r["library_iv"]["terms"]) or "(intercept only)" for r in rows if "library_iv" in r)
            w(f"\nSRIT-style kept inputs: {dict(srit)}. Library IV term sets (top 3): "
              + "; ".join(f"{t} ×{c}" for t, c in lib.most_common(3)) + ".\n")

    if n_err:
        w("\n## Method errors\n")
        for k, m in sorted(runs.items()):
            for name, tb in m["_errors"].items():
                w(f"- {k}: {name}: `{tb.strip().splitlines()[-1]}`")

    (HERE / "phase3" / "summary.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
